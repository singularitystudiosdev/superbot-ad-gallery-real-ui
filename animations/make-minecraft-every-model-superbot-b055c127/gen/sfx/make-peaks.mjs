// Rebuild gen/sfx/peaks.js from the CC0 audio sitting next to it (node gen/sfx/make-peaks.mjs).
// Each clip is decoded to mono 16 kHz PCM with ffmpeg, its leading and trailing silence (below FLOOR dBFS) is
// trimmed the way an audio editor's waveform view crops it, then the rest is cut into BARS buckets. A bucket's
// peak amplitude, read on a dB scale from FLOOR to 0 dBFS (what editors call a log waveform), becomes one bar.
// The beat only ever reads peaks.js, so every bar is measured audio, not a drawn shape.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const BARS = 56;
const RATE = 16000;
const FLOOR = -54; // dBFS: quieter than this reads as silence, both for the trim and as the bars' baseline
const CLIPS = ['footstep_grass_000', 'impactMining_000', 'chop', 'impactSoft_heavy_000', 'doorOpen_1'];

const pcm = (f) => execFileSync('ffmpeg', ['-v', 'error', '-i', f, '-ac', '1', '-ar', String(RATE), '-f', 's16le', '-'], { maxBuffer: 1 << 28 });
const db = (v) => (v > 0 ? 20 * Math.log10(v) : -120);

const out = {};
for (const name of CLIPS) {
  const buf = pcm(join(HERE, `${name}.ogg`));
  const n = buf.length >> 1;
  const s = new Float32Array(n);
  for (let i = 0; i < n; i++) s[i] = Math.abs(buf.readInt16LE(i << 1)) / 32768;
  let top = 0;
  for (let i = 0; i < n; i++) if (s[i] > top) top = s[i];
  const gate = top * 10 ** (FLOOR / 20);
  let a = 0, b = n - 1;
  while (a < n && s[a] < gate) a++;
  while (b > a && s[b] < gate) b--;
  const len = b - a + 1;
  const peaks = [];
  for (let k = 0; k < BARS; k++) {
    const i0 = a + Math.floor((k * len) / BARS), i1 = a + Math.floor(((k + 1) * len) / BARS);
    let m = 0;
    for (let i = i0; i < i1; i++) if (s[i] > m) m = s[i];
    const d = db(m / top); // relative to the clip's own loudest sample
    peaks.push(Number(Math.max(0.06, Math.min(1, (d - FLOOR) / -FLOOR)).toFixed(3)));
  }
  out[name] = { file: `${name}.ogg`, dur: Number((n / RATE).toFixed(3)), shown: Number((len / RATE).toFixed(3)), peaks };
  console.error(`${name}: ${out[name].dur}s, ${out[name].shown}s shown`);
}
const body = `// Generated by make-peaks.mjs: per clip, its full duration, the stretch shown once silence is trimmed, and
// ${BARS} waveform bars (0-1, peak level on a ${FLOOR}..0 dBFS scale), measured with ffmpeg from the CC0 audio beside this
// file. Data only, so the beat stays a pure function of t. Sources and licences: CREDITS.txt.
export default {
${Object.entries(out).map(([k, v]) => `  ${k}: { file: '${v.file}', dur: ${v.dur}, shown: ${v.shown}, peaks: [${v.peaks.join(',')}] },`).join('\n')}
};
`;
writeFileSync(join(HERE, 'peaks.js'), body);
console.error(`wrote ${Object.keys(out).length} clips to peaks.js`);
