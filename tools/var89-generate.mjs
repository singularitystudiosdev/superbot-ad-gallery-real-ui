// var89-generate.mjs: build the 12 variant folders of the we-dont-care spot from tools/var89-matrix.mjs.
//
//   node tools/var89-generate.mjs            # writes animations/<id>/ for every matrix cell
//
// Each folder is a byte copy of animations/we-dont-care-gamble-superbot-89be2ca4/ with its own variant.js
// (the matrix cell merged over the base's variant.js defaults) and its own img/CREDITS.txt. Nothing else in a
// generated folder differs from the base spot, so the confetti, the slam, the timings, the layout and the end
// card are the same ad; only the voice on card 1 and the provider content pack change.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { BASE_ID, VARIANTS } from './var89-matrix.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const BASE = join(ROOT, 'animations', BASE_ID);

if (!existsSync(join(BASE, 'variant.js'))) throw new Error(`base spot not parameterized: ${BASE}/variant.js is missing`);
const defaults = (await import(pathToFileURL(join(BASE, 'variant.js')).href)).default;

const js = (o) => `export default ${JSON.stringify(o, null, 2)};\n`;

const variantFile = (v) => `// GENERATED by tools/var89-generate.mjs from tools/var89-matrix.mjs — do not hand-edit this folder.
// This is animations/${BASE_ID}/ with the values below; every other file in the folder is that spot unchanged.
${js({
    id: v.id,
    voice: v.voice,
    introLine: v.introLine,
    redWord: v.redWord,
    slamLine: v.slamLine,
    ask: v.ask,
    say: v.say,
    workTitle: v.workTitle,
    site: { ...defaults.site, ...v.site },
    steps: v.steps,
  })}`;

const creditsFile = (v) => `img CREDITS (${v.id})

This spot ships no photographic or third-party image assets. Everything on screen — the hub chrome, the tray
of app tiles, the wins site's chrome, its chart, its payout rows and the confetti burst — is drawn in
CSS/SVG/canvas from code in this folder.

The ${v.credits} The account it would have come from is the ${v.voice} voice on the first card: a fictional
assistant quoting advice, not an offer. ${v.site.slug} is a fictional address and no game, odds, payout or
bonus is shown or promised anywhere in the spot.
`;

const written = [];
for (const v of VARIANTS) {
  if (v.id === BASE_ID) throw new Error(`variant id collides with the base: ${v.id}`);
  const dir = join(ROOT, 'animations', v.id);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  cpSync(BASE, dir, { recursive: true });
  writeFileSync(join(dir, 'variant.js'), variantFile(v));
  writeFileSync(join(dir, 'img', 'CREDITS.txt'), creditsFile(v));
  // sanity: the copy really is the base spot (only variant.js / CREDITS.txt may differ)
  const same = readFileSync(join(BASE, 'timeline.js'), 'utf8') === readFileSync(join(dir, 'timeline.js'), 'utf8')
    && readFileSync(join(BASE, 'scenes/tabs-assets/beats/winnings.js'), 'utf8') === readFileSync(join(dir, 'scenes/tabs-assets/beats/winnings.js'), 'utf8');
  if (!same) throw new Error(`${v.id}: copied tree does not match the base spot`);
  written.push(dir);
}
console.log(`generated ${written.length} variants from ${BASE_ID}:`);
written.forEach((d) => console.log('  ' + d.replace(ROOT + '/', '')));